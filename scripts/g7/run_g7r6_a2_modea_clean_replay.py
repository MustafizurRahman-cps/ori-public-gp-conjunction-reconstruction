def load_module(relative: str, name: str):
    path = root() / relative
    require(relative not in ACQUISITION_DENYLIST, f"deny-listed acquisition script: {relative}")
    require(path.is_file(), f"missing module: {relative}")
    spec = importlib.util.spec_from_file_location(name, path)
    require(spec is not None and spec.loader is not None, f"cannot load module: {relative}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    require(Path(module.__file__).resolve() == path.resolve(), f"unexpected import target: {relative}")
    return module


def load_checkpoint(stage: str, verify_outputs: bool = True) -> dict[str, Any]:
    cp = load_json(checkpoint_path(stage))
    require(cp.get("status") == "COMPLETE_VALIDATED", f"{stage} checkpoint not validated")
    if verify_outputs:
        for item in cp.get("outputs", []):
            p = root() / item["path"]
            require(p.is_file(), f"{stage} output missing: {item['path']}")
            require(sha256(p) == item["sha256"], f"{stage} output identity changed: {item['path']}")
    return cp


