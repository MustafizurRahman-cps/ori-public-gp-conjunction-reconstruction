def _verify_controller_inputs(controller) -> dict[str, str]:
    current = generated_hash_map("S01", "S16")
    value = getattr(controller, "EXPECTED_HASHES", {})
    require(isinstance(value, dict), "controller EXPECTED_HASHES missing")
    observed = {}
    for p, expected in value.items():
        rp = p.relative_to(controller.ROOT).as_posix()
        if rp in current:
            require(p.is_file(), f"controller regenerated dependency missing: {rp}")
            actual = sha256(p)
            require(actual == current[rp], f"controller regenerated hash mismatch: {rp}")
            observed[rp] = actual
        elif p.is_file():
            actual = sha256(p)
            require(actual == expected, f"controller immutable dependency changed: {rp}")
            observed[rp] = actual
        elif rp.startswith(("results/g6/", "results/g7/")):
            # Historical governance/result evidence is not a Mode-A initialization input.
            continue
        else:
            raise ModeAHold(f"controller required dependency missing: {rp}")
    observed["mode_a_s16_checkpoint"] = sha256(checkpoint_path("S16"))
    return observed


