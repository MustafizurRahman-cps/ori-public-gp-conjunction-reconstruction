def quote_ident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def encode_sql_value(value: Any) -> bytes:
    if value is None:
        return b"N;"
    if isinstance(value, bytes):
        return b"B" + str(len(value)).encode() + b":" + value + b";"
    if isinstance(value, int):
        return b"I" + str(value).encode() + b";"
    if isinstance(value, float):
        return b"F" + repr(value).encode() + b";"
    raw = str(value).encode("utf-8")
    return b"S" + str(len(raw)).encode() + b":" + raw + b";"


def sqlite_logical_summary(path: Path) -> dict[str, Any]:
    con = sqlite3.connect(path.resolve().as_uri() + "?mode=ro", uri=True)
    try:
        quick = str(con.execute("PRAGMA quick_check").fetchone()[0])
        require(quick == "ok", f"SQLite quick_check failed: {rel(path)}")
        tables = [
            row[0]
            for row in con.execute(
                "SELECT name FROM sqlite_master "
                "WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
            )
        ]
        out: dict[str, Any] = {"quick_check": quick, "tables": {}}
        for table in tables:
            info = con.execute(f"PRAGMA table_info({quote_ident(table)})").fetchall()
            cols = [str(row[1]) for row in info]
            pk = [str(row[1]) for row in sorted(info, key=lambda x: int(x[5])) if int(row[5]) > 0]
            order_cols = pk if pk else cols
            count = int(con.execute(f"SELECT COUNT(*) FROM {quote_ident(table)}").fetchone()[0])
            schema_row = con.execute(
                "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()
            schema = "" if schema_row is None or schema_row[0] is None else str(schema_row[0])
            h = hashlib.sha256()
            h.update(schema.encode("utf-8"))
            h.update(b"\n")
            select = f"SELECT * FROM {quote_ident(table)}"
            if order_cols:
                select += " ORDER BY " + ",".join(quote_ident(c) for c in order_cols)
            cur = con.execute(select)
            while True:
                rows = cur.fetchmany(1000)
                if not rows:
                    break
                for row in rows:
                    for value in row:
                        h.update(encode_sql_value(value))
                    h.update(b"\n")
            out["tables"][table] = {
                "rows": count,
                "columns": cols,
                "order_key": order_cols,
                "logical_sha256": h.hexdigest(),
            }
        return out
    finally:
        con.close()


def seal_stage(
    stage: str,
    *,
    extra_outputs: list[str] | None = None,
    logical_sqlite: set[str] | None = None,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    logical_sqlite = logical_sqlite or set()
    paths = list(OUTPUTS[stage])
    if extra_outputs:
        for p in extra_outputs:
            if p not in paths:
                paths.append(p)
    manifest = []
    for rp in paths:
        p = root() / rp
        require(p.is_file(), f"{stage} expected output missing: {rp}")
        item: dict[str, Any] = {
            "path": rp,
            "bytes": p.stat().st_size,
            "sha256": sha256(p),
        }
        if p.suffix.lower() in {".sqlite", ".sqlite3", ".db"}:
            con = sqlite3.connect(p)
            try:
                con.execute("PRAGMA wal_checkpoint(TRUNCATE)")
            finally:
                con.close()
            item["bytes"] = p.stat().st_size
            item["sha256"] = sha256(p)
            if rp in logical_sqlite:
                item["logical_sqlite"] = sqlite_logical_summary(p)
            else:
                con = sqlite3.connect(p.resolve().as_uri() + "?mode=ro", uri=True)
                try:
                    item["sqlite_quick_check"] = str(con.execute("PRAGMA quick_check").fetchone()[0])
                    require(item["sqlite_quick_check"] == "ok", f"SQLite quick_check failed: {rp}")
                finally:
                    con.close()
        manifest.append(item)
    payload = {
        "status": "COMPLETE_VALIDATED",
        "stage": stage,
        "mode": "A",
        "initialization_head": INITIALIZATION_HEAD,
        "initialization_tag": INITIALIZATION_TAG,
        "implementation_sha256": sha256(Path(__file__)),
        "environment": verify_environment(),
        "upstream_checkpoint_sha256": {
            s: sha256(checkpoint_path(s))
            for s in STAGES
            if checkpoint_path(s).is_file() and int(s[1:]) < int(stage[1:])
        },
        "outputs": manifest,
        "scientific_logic_changed": False,
        "network_access": False,
        "A0_executed": False,
        "secondary_14d_60d_executed": False,
        "extra": extra or {},
    }
    atomic_json(checkpoint_path(stage), payload)
    return payload


def _path_rel_for_module(module, p: Path) -> str | None:
    try:
        return p.resolve().relative_to(Path(module.ROOT).resolve()).as_posix()
    except Exception:
        return None


def redirect_exact_paths(module, mapping: dict[str, str]) -> None:
    def remap(value):
        if isinstance(value, Path):
            rp = _path_rel_for_module(module, value)
            if rp in mapping:
                return Path(module.ROOT) / mapping[rp]
            return value
        if isinstance(value, dict):
            return {remap(k): remap(v) for k, v in value.items()}
        if isinstance(value, list):
            return [remap(v) for v in value]
        if isinstance(value, tuple):
            return tuple(remap(v) for v in value)
        if isinstance(value, set):
            return {remap(v) for v in value}
        return value

    for name, value in list(vars(module).items()):
        if name.startswith("__"):
            continue
        if isinstance(value, (Path, dict, list, tuple, set)):
            try:
                setattr(module, name, remap(value))
            except Exception:
                pass


def replace_scalar_sha(module, old: str, new: str) -> int:
    count = 0
    for name, value in list(vars(module).items()):
        if isinstance(value, str) and value.lower() == old.lower():
            setattr(module, name, new)
            count += 1
    return count


def adapt_path_hash_dict(
    module,
    attr_name: str,
    current: dict[str, str],
    *,
    drop_missing_historical_results: bool = True,
) -> dict[str, str]:
    value = getattr(module, attr_name, None)
    if not isinstance(value, dict):
        return {}
    if not all(isinstance(k, Path) and isinstance(v, str) for k, v in value.items()):
        return {}

    new = {}
    observed = {}
    for p, expected in value.items():
        rp = _path_rel_for_module(module, p)
        if rp is None:
            new[p] = expected
            continue
        if rp in current:
            require(p.is_file(), f"regenerated input missing: {rp}")
            actual = sha256(p)
            require(actual == current[rp], f"regenerated checkpoint hash mismatch: {rp}")
            new[p] = actual
            observed[rp] = actual
            continue
        if p.is_file():
            actual = sha256(p)
            require(actual == expected, f"immutable input SHA mismatch: {rp}")
            new[p] = expected
            observed[rp] = actual
            continue
        if drop_missing_historical_results and rp.startswith(("results/g6/", "results/g7/")):
            # Historical result/governance evidence is not a Mode-A initialization input.
            continue
        raise ModeAHold(f"required frozen dependency missing: {rp}")

    setattr(module, attr_name, new)
    return observed


def adapt_known_hash_dicts(module, current: dict[str, str]) -> dict[str, str]:
    observed = {}
    for name in ("EXPECTED_HASHES", "FROZEN_SMALL_INPUTS", "EXPECTED_INPUT_HASHES"):
        observed.update(adapt_path_hash_dict(module, name, current))
    return observed


def run_script_body(relative: str) -> None:
    require(relative not in ACQUISITION_DENYLIST, f"deny-listed script: {relative}")
    path = root() / relative
    require(path.is_file(), f"direct stage script missing: {relative}")
    old_argv = sys.argv[:]
    old_cwd = Path.cwd()
    try:
        # Several frozen direct-stage scripts intentionally define ROOT = Path.cwd().
        # Execute them from the non-Git Mode-A clean root so their scientific
        # inputs and generated outputs remain inside the isolated replay workspace.
        os.chdir(root())
        sys.argv = [str(path)]
        try:
            runpy.run_path(str(path), run_name="__main__")
        except SystemExit as exc:
            require(exc.code in (None, 0), f"{relative} exited with {exc.code}")
    finally:
        sys.argv = old_argv
        os.chdir(old_cwd)


