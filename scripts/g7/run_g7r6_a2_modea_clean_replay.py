def execute_stage(stage: str) -> None:
    verify_initialization()
    install_network_guard()

    idx = STAGES.index(stage)
    if idx > 0:
        previous = STAGES[idx - 1]
        require(
            checkpoint_path(previous).is_file(),
            f"cannot execute {stage} before {previous}",
        )
        load_checkpoint(previous)

    print("=" * 68, flush=True)
    print(f"MODE_A_STAGE_START = {stage}", flush=True)
    print("=" * 68, flush=True)
    t0 = time.perf_counter()

    RUNNERS[stage]()

    cp = load_checkpoint(stage)
    cp["wall_seconds_orchestrator"] = time.perf_counter() - t0
    atomic_json(checkpoint_path(stage), cp)

    print("=" * 68, flush=True)
    print(f"MODE_A_STAGE = {stage} PASS", flush=True)
    print(f"CHECKPOINT = {checkpoint_path(stage)}", flush=True)
    print(f"WALL_SECONDS = {cp['wall_seconds_orchestrator']:.3f}", flush=True)
    print("=" * 68, flush=True)


def resume_all() -> None:
    verify_initialization()
    install_network_guard()

    completed = []
    for stage in STAGES:
        cp_path = checkpoint_path(stage)
        if cp_path.is_file():
            cp = load_checkpoint(stage)
            if cp.get("status") == "COMPLETE_VALIDATED":
                print(f"MODE_A_STAGE_REUSE = {stage}", flush=True)
                completed.append(stage)
                continue

        execute_stage(stage)
        completed.append(stage)

    payload = {
        "status": "MODE_A_S01_S20_COMPLETE",
        "completed_stages": completed,
        "scientific_logic_changed": False,
        "network_access": False,
        "A0_executed": False,
        "secondary_14d_60d_executed": False,
        "reference_comparison_executed": False,
        "next_action": "V99_POSTCOMPUTE_SCIENTIFIC_EQUIVALENCE",
    }
    atomic_json(root() / "audit/mode_a_s01_s20_completion.json", payload)
    print(json.dumps(payload, indent=2, sort_keys=True))


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--static-validate", action="store_true")
    group.add_argument("--stage", choices=STAGES)
    group.add_argument("--resume-all", action="store_true")
    args = parser.parse_args()

    try:
        if args.static_validate:
            print(json.dumps(static_validate(), indent=2, sort_keys=True))
            return 0
        if args.stage:
            execute_stage(args.stage)
            return 0
        if args.resume_all:
            resume_all()
            return 0
        raise AssertionError("unreachable")
    except Exception as exc:
        payload = {
            "status": "HOLD",
            "exception_type": type(exc).__name__,
            "message": str(exc),
            "scientific_logic_changed": False,
            "network_access": False,
        }
        print(json.dumps(payload, indent=2, sort_keys=True), file=sys.stderr)
        try:
            r = root()
            if (r / "checkpoints/m00.json").is_file():
                atomic_json(r / "audit/mode_a_hold.json", payload)
        except Exception:
            pass
        return 2


